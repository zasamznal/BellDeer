const dicts: Record<Lang, Dict> = { en, ru };
let lang: Lang = 'en';

export function setLang(l: Lang): void {
  lang = l;
  document.documentElement.lang = l;
}
export function getLang(): Lang {
  return lang;
}
/** English by default; Russian when the browser (or the platform SDK) says so. */
export function detectLang(): Lang {
  const n = (navigator.languages?.[0] ?? navigator.language ?? 'en').toLowerCase();
  return n.startsWith('ru') || n.startsWith('be') || n.startsWith('uk') || n.startsWith('kk') ? 'ru' : 'en';
}
export function t(key: string, vars?: Record<string, string | number>): string {
  let s = dicts[lang][key] ?? en[key] ?? key;
  if (vars) for (const k in vars) s = s.replace(`{${k}}`, String(vars[k]));
  return s;
}
/** Localise a value from the card table: units and decimal comma. */
export function val(v: string): string {
  if (lang !== 'ru') return v;
  return v.replace(/m\/s/g, 'м/с').replace(/(\d) s\b/g, '$1 с').replace(/(\d) m\b/g, '$1 м').replace(/(\d)\.(\d)/g, '$1,$2');
}
